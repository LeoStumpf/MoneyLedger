#!/usr/bin/env python3
"""Generates lib/core/l10n/currency_names.dart (G66): the active ISO-4217
currency codes with English + German names.

Source: the Debian/freedesktop `iso-codes` package (LGPL-2.1-or-later) —
/usr/share/iso-codes/json/iso_4217.json and its German gettext catalogue
(/usr/share/locale/de/LC_MESSAGES/iso_4217.mo). Fund / metal / test codes and
withdrawn currencies are left out; a few ISO names that don't say which
country they belong to ("Yen", "Won") get a clearer name (OVERRIDES).

Run once when the data should be refreshed, then `dart format`:
    python3 tool/currencies/make_currency_names.py
"""
import gettext
import json
import pathlib

ISO_JSON = '/usr/share/iso-codes/json/iso_4217.json'
OUT = pathlib.Path(__file__).resolve().parents[2] / 'lib/core/l10n/currency_names.dart'

# Not a currency people pay with (funds, metals, units of account, test
# codes) or withdrawn (HRK → EUR 2023, SLL → SLE, ZWL, CUC, VED duplicate).
EXCLUDED = {
    'BOV', 'CHE', 'CHW', 'CLF', 'COU', 'MXV', 'USN', 'UYI', 'UYW',
    'XAG', 'XAU', 'XBA', 'XBB', 'XBC', 'XBD', 'XDR', 'XPD', 'XPT', 'XSU',
    'XTS', 'XUA', 'XXX', 'HRK', 'SLL', 'ZWL', 'CUC', 'VED',
}

# code: (English, German) — clearer than the bare ISO names.
OVERRIDES = {
    'JPY': ('Japanese Yen', 'Japanischer Yen'),
    'KRW': ('South Korean Won', 'Südkoreanischer Won'),
    'CNY': ('Chinese Yuan Renminbi', 'Chinesischer Renminbi-Yuan'),
    'THB': ('Thai Baht', 'Thailändischer Baht'),
    'HUF': ('Hungarian Forint', 'Ungarischer Forint'),
    'PLN': ('Polish Zloty', 'Polnischer Złoty'),
    'IDR': ('Indonesian Rupiah', 'Indonesische Rupiah'),
    'VND': ('Vietnamese Dong', 'Vietnamesischer Dong'),
    'ZAR': ('South African Rand', 'Südafrikanischer Rand'),
    'GEL': ('Georgian Lari', 'Georgischer Lari'),
    'MKD': ('Macedonian Denar', 'Mazedonischer Denar'),
    'ALL': ('Albanian Lek', 'Albanischer Lek'),
    'ISK': ('Icelandic Krona', 'Isländische Krone'),
    'TRY': ('Turkish Lira', 'Türkische Lira'),
    'UAH': ('Ukrainian Hryvnia', 'Ukrainische Hrywnja'),
    'KZT': ('Kazakhstani Tenge', 'Kasachischer Tenge'),
    'KHR': ('Cambodian Riel', 'Kambodschanischer Riel'),
    'PEN': ('Peruvian Sol', 'Peruanischer Sol'),
    'BDT': ('Bangladeshi Taka', 'Bangladesch-Taka'),
    'MMK': ('Myanmar Kyat', 'Myanmar-Kyat'),
    'BAM': ('Bosnia-Herzegovina Convertible Mark', 'Bosnisch-herzegowinische Konvertible Mark'),
}


def dart_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main():
    de = gettext.translation('iso_4217', localedir='/usr/share/locale', languages=['de'])
    entries = json.load(open(ISO_JSON, encoding='utf-8'))['4217']
    rows = []
    for e in sorted(entries, key=lambda e: e['alpha_3']):
        code = e['alpha_3']
        if code in EXCLUDED:
            continue
        en_name, de_name = OVERRIDES.get(code, (e['name'], de.gettext(e['name'])))
        rows.append(f'  {dart_str(code)}: ({dart_str(en_name)}, {dart_str(de_name)}),')
    OUT.write_text(
        '// GENERATED by tool/currencies/make_currency_names.py — do not edit.\n'
        '// Data: iso-codes (ISO 4217 names + German translations),\n'
        '// LGPL-2.1-or-later — see THIRD_PARTY_NOTICES.md.\n\n'
        '/// G66: active ISO-4217 currency codes → (English, German) name.\n'
        'const kCurrencyNames = <String, (String, String)>{\n'
        + '\n'.join(rows)
        + '\n};\n',
        encoding='utf-8',
    )
    print(f'{len(rows)} currencies → {OUT}')


if __name__ == '__main__':
    main()
